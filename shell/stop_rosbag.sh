#!/bin/bash

set -e

BASE_DIR="/home/kane/siasun/siasun_test"

PID_FILE="${BASE_DIR}/run/siasun_recorder.pid"

# =========================================================
# pid 文件检查
# =========================================================

if [ ! -f "${PID_FILE}" ]; then

    echo "[错误] pid 文件不存在"

    exit 1
fi

PID=$(cat "${PID_FILE}")

# =========================================================
# 进程检查
# =========================================================

if ! ps -p "${PID}" > /dev/null 2>&1; then

    echo "[错误] recorder 未运行"

    rm -f "${PID_FILE}"

    exit 1
fi

echo "================================================"

echo "[停止] recorder pid=${PID}"

echo "================================================"

# =========================================================
# 发送 SIGTERM
# =========================================================

kill -TERM -- -"${PID}"

# =========================================================
# 等待退出
# =========================================================

TIMEOUT=20

while ps -p "${PID}" > /dev/null 2>&1; do

    if [ "${TIMEOUT}" -le 0 ]; then

        echo "[警告] recorder 未退出，强制 kill"

        kill -KILL -- -"${PID}" || true

        break
    fi

    sleep 1

    TIMEOUT=$((TIMEOUT - 1))
done

# =========================================================
# 清理 pid 文件
# =========================================================

rm -f "${PID_FILE}"

echo "[停止] 完成"

